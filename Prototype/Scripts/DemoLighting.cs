using System.Collections;
using System.Collections.Generic;
using UnityEngine;
using UnityEngine.XR;

// Lighting presets for the instructor: the shop as found by day, or the same
// shop at night with the lights dimmed, the ceiling fixtures dark and the fog
// closer, plus two handheld torches: the white flashlight (desktop view or right
// hand) and the UV torch (desktop view or left hand). This component is the one
// owner of what is in the hand: by default the torches exclude each other, so the
// fluorescence of the authored UV traces (UVTrace) reads against darkness. The
// originals are collected once from the scene and restored exactly; a session
// reset returns to day with both torches off and the UV example traces hidden.
//
// A baked night scene (BakedNight, set by its lighting pass) starts at night and
// never touches its baked lights: "day" there is a diagnostic daylight, a shadowless
// realtime DiagnosticSun and a grey flat ambient, so the instructor can compare the
// layout with the reference; night switches both off again, and a reset returns to night.
public sealed class DemoLighting : MonoBehaviour
{
    public DemoSession Session;
    public float TransitionSeconds = 1f;
    public float NightLightFactor = 0.25f;
    public float NightAmbientFactor = 0.3f;
    public float NightFogFactor = 0.35f;
    public Color FlashlightColor = new Color(1f, 0.95f, 0.85f);
    public float FlashlightIntensity = 2.2f;
    // UV torch: a narrow violet spot without shadows; UVTrace and the UVFluorescence
    // shader read its cone and range, so the glow follows the beam it is seen in.
    public Color UVColor = new Color(0.38f, 0.12f, 1f);
    public float UVIntensity = 0.8f;
    public float UVRange = 6;
    public float UVSpotAngle = 32;
    public bool TorchesExclusive = true;
    // Authored placeholder traces (the night store's UVTraceExamples), hidden until the
    // instructor shows them; null in scenes without examples.
    public GameObject UVExamples;
    public bool BakedNight;
    public Light DiagnosticSun;
    public Color DiagnosticAmbient = new Color(0.35f, 0.35f, 0.35f);
    // Assigned by the texture pass when the dusk panorama is present; day sky kept from the scene.
    public Material NightSky;
    // Spot cookie (hotspot, soft falloff, faint outer ring) generated by DemoToolsBuilder.
    public Texture FlashlightCookie;
    // Where a torch sits on its holder: the lens in front of the hand in VR. On the
    // desktop view the light and the model are placed apart: the light just below the
    // eye and the model bottom-right (below and left of a held camera body), both
    // within the player's 0.23 m capsule so neither passes through a wall the presenter
    // walks up to. The UV torch uses the same offsets mirrored to the left.
    public Vector3 HandLensOffset = new Vector3(0, 0.035f, 0.1f);
    public Vector3 ViewLightOffset = new Vector3(0.06f, -0.08f, 0.05f);
    public Vector3 ViewModelOffset = new Vector3(0.1f, -0.12f, 0.22f);
    public float ViewModelScale = 0.6f;

    public bool Night { get; private set; }
    public Light FlashlightLight => white.Light;
    // The white torch model, pivot at the lens: a child of the light in the hand,
    // a child of the view on the desktop.
    public GameObject FlashlightModel => white.Model;
    public bool FlashlightOn => white.On;
    public Light UVTorchLight => uv.Light;
    public GameObject UVTorchModel => uv.Model;
    public bool UVTorchOn => uv.On;
    public bool UVExamplesVisible => UVExamples != null && UVExamples.activeSelf;

    // Shader globals the UVFluorescence shader reads: position, direction and
    // (cos of the half outer angle, range, 1 when on).
    public static readonly int UVPositionId = Shader.PropertyToID("_UVTorchPosition");
    public static readonly int UVDirectionId = Shader.PropertyToID("_UVTorchDirection");
    public static readonly int UVParamsId = Shader.PropertyToID("_UVTorchParams");

    private const string FixtureName = "CeilingLight";
    private const string EmissionProperty = "_EmissionColor";

    private Light[] lights = new Light[0];
    private float[] intensities = new float[0];
    private Renderer[] fixtures = new Renderer[0];
    private Color[] emissions = new Color[0];
    private Color sky, equator, ground, fogColor, background, nightAmbient;
    private Material daySky;
    private float ambientIntensity, fogStart, fogEnd, fogDensity;
    private Camera view;
    private DemoModeSwitch mode;
    private bool collected;
    // 0 is day, 1 is night; the transition moves it between the two.
    private float blend;
    private Coroutine transition;
    private static MaterialPropertyBlock block;

    // One handheld torch: its spot light, the model and which holder it is on.
    private sealed class Torch
    {
        public Light Light;
        public GameObject Model;
        public Renderer[] Parts = new Renderer[0];
        public bool InVR, Hidden, Ultraviolet;
        public XRNode Hand;
        public bool On => Light != null && Light.enabled && Light.gameObject.activeSelf;
    }

    private readonly Torch white = new Torch { Hand = XRNode.RightHand };
    private readonly Torch uv = new Torch { Hand = XRNode.LeftHand, Ultraviolet = true };

    private void Awake() { if (BakedNight) Night = true; }

    private void Start() { Collect(); }

    private void OnEnable()
    {
        if (Session != null) Session.SessionReset.AddListener(OnReset);
    }

    private void OnDisable()
    {
        if (Session != null) Session.SessionReset.RemoveListener(OnReset);
    }

    private void OnReset()
    {
        if (Night != BakedNight) SetNight(BakedNight);
        Flashlight(false);
        UVTorch(false);
        SetUVExamples(false);
    }

    // The torches follow the active mode (F9 may switch it while one is on); the UV
    // torch publishes its beam and updates the traces every frame while it is on.
    private void Update()
    {
        bool vr = mode != null && mode.VRActive;
        if (white.On && mode != null && vr != white.InVR) Attach(white);
        if (uv.On && mode != null && vr != uv.InVR) Attach(uv);
        if (uv.On) UpdateUV(Time.deltaTime);
    }

    public void ToggleNight() { SetNight(!Night); }

    public void SetNight(bool night)
    {
        Collect();
        Night = night;
        if (BakedNight) { Diagnostic(!night); return; }
        if (transition != null) StopCoroutine(transition);
        transition = null;
        if (TransitionSeconds > 0 && isActiveAndEnabled) transition = StartCoroutine(Transition(night ? 1 : 0));
        else Apply(night ? 1 : 0);
    }

    // Baked night: the switch is immediate (lightmaps cannot fade), and only the sun
    // and the flat ambient change, so night is restored exactly.
    private void Diagnostic(bool day)
    {
        if (DiagnosticSun != null) DiagnosticSun.enabled = day;
        RenderSettings.ambientLight = day ? DiagnosticAmbient : nightAmbient;
    }

    // Finishes the running transition at once; validation uses it, a presenter never needs to.
    public void Complete()
    {
        if (BakedNight) return;
        if (transition != null) StopCoroutine(transition);
        transition = null;
        Apply(Night ? 1 : 0);
    }

    private IEnumerator Transition(float target)
    {
        float from = blend;
        for (float t = 0; t < 1; t += Time.unscaledDeltaTime / TransitionSeconds)
        {
            Apply(Mathf.Lerp(from, target, t));
            yield return null;
        }
        Apply(target);
        transition = null;
    }

    private void Apply(float k)
    {
        blend = k;
        float light = Mathf.Lerp(1, NightLightFactor, k), ambient = Mathf.Lerp(1, NightAmbientFactor, k), fog = Mathf.Lerp(1, NightFogFactor, k);
        for (int i = 0; i < lights.Length; i++)
            if (lights[i] != null) lights[i].intensity = intensities[i] * light;
        if (block == null) block = new MaterialPropertyBlock();
        for (int i = 0; i < fixtures.Length; i++)
        {
            if (fixtures[i] == null) continue;
            block.Clear();
            // By day the block stays empty so the saved material shows untouched.
            if (k > 0) block.SetColor(EmissionProperty, Color.Lerp(emissions[i], Color.black, k));
            fixtures[i].SetPropertyBlock(block);
        }
        RenderSettings.ambientSkyColor = sky * ambient;
        RenderSettings.ambientLight = sky * ambient;
        RenderSettings.ambientEquatorColor = equator * ambient;
        RenderSettings.ambientGroundColor = ground * ambient;
        RenderSettings.ambientIntensity = ambientIntensity * ambient;
        // Night fog: darker and closer, so the street fades a few metres beyond the window.
        RenderSettings.fogColor = fogColor * fog;
        RenderSettings.fogStartDistance = fogStart * Mathf.Lerp(1, 0.6f, k);
        RenderSettings.fogEndDistance = fogEnd * Mathf.Lerp(1, 0.6f, k);
        RenderSettings.fogDensity = fogDensity * Mathf.Lerp(1, 1.6f, k);
        if (view != null) view.backgroundColor = background * fog;
        // The sky swaps to the dusk panorama past the midpoint of the fade.
        if (NightSky != null && daySky != null) RenderSettings.skybox = k > 0.5f ? NightSky : daySky;
    }

    // Originals, taken once: every scene light except the torches, the ceiling
    // fixtures' emission, the ambient trilight, the fog and the view's clear colour.
    private void Collect()
    {
        if (collected) return;
        collected = true;
        List<Light> found = new List<Light>();
        foreach (Light l in FindObjectsByType<Light>(FindObjectsSortMode.None))
            if (l != white.Light && l != uv.Light && l != DiagnosticSun) found.Add(l);
        lights = found.ToArray();
        intensities = new float[lights.Length];
        for (int i = 0; i < lights.Length; i++) intensities[i] = lights[i].intensity;
        List<Renderer> lit = new List<Renderer>();
        foreach (MeshRenderer r in FindObjectsByType<MeshRenderer>(FindObjectsSortMode.None))
            if (r.name == FixtureName && r.sharedMaterial != null && r.sharedMaterial.HasProperty(EmissionProperty)) lit.Add(r);
        fixtures = lit.ToArray();
        emissions = new Color[fixtures.Length];
        for (int i = 0; i < fixtures.Length; i++) emissions[i] = fixtures[i].sharedMaterial.GetColor(EmissionProperty);
        sky = RenderSettings.ambientSkyColor;
        nightAmbient = RenderSettings.ambientLight; // A baked night returns to it after diagnostic daylight.
        equator = RenderSettings.ambientEquatorColor;
        ground = RenderSettings.ambientGroundColor;
        ambientIntensity = RenderSettings.ambientIntensity;
        fogColor = RenderSettings.fogColor;
        fogStart = RenderSettings.fogStartDistance;
        fogEnd = RenderSettings.fogEndDistance;
        fogDensity = RenderSettings.fogDensity;
        // Only a view clearing to a colour is dimmed; a skybox is left as it is.
        view = Camera.main != null && Camera.main.clearFlags == CameraClearFlags.SolidColor ? Camera.main : null;
        if (view != null) background = view.backgroundColor;
        daySky = RenderSettings.skybox;
        mode = FindFirstObjectByType<DemoModeSwitch>();
    }

    // Instructor and visitor toggles click (recorded switch from a DemoSoundBank, silent
    // without one); Flashlight/UVTorch themselves stay silent for resets and scripts.
    public void ToggleFlashlight() { Flashlight(!FlashlightOn); SwitchSound(white); }

    // Warm spot light at the lens of a visible torch model, created on first use and
    // re-attached whenever it is switched on, since the holder depends on the mode at
    // that moment. Low-resolution hard shadows: the one realtime shadow in the night
    // scene, so objects in the beam occlude it and the beam reads as handheld.
    public void Flashlight(bool on)
    {
        if (on && TorchesExclusive) UVTorch(false);
        Switch(white, on);
        // The flashlight takes the one realtime shadow from a lit scene lamp, and hands it back.
        if (Session != null && Session.Station != null) Session.Station.UpdateLampShadows();
    }

    public void ToggleUVTorch() { UVTorch(!UVTorchOn); SwitchSound(uv); }

    private void SwitchSound(Torch torch)
    {
        Vector3 at = torch.Light != null ? torch.Light.transform.position : transform.position;
        DemoSounds.Play(DemoSound.Switch, at, 0.25f);
    }

    // Violet spot without shadows (the trace's own line-of-sight test keeps the glow
    // out of occluded places); switching it off darkens every trace at once.
    public void UVTorch(bool on)
    {
        if (on && TorchesExclusive) Flashlight(false);
        Switch(uv, on);
        if (on) UpdateUV(0);
        else if (uv.Light != null)
        {
            Shader.SetGlobalVector(UVParamsId, Vector4.zero);
            UVTrace.HideAll();
        }
    }

    public void ToggleUVExamples() { SetUVExamples(!UVExamplesVisible); }

    public void SetUVExamples(bool visible)
    {
        if (UVExamples != null) UVExamples.SetActive(visible);
    }

    // Runs the trace update with the smoothing completed at once, for validation; a
    // presenter sees the same result fade in over UVTrace.FadeSeconds.
    public void SettleUVTraces()
    {
        if (UVTorchOn) UpdateUV(UVTrace.FadeSeconds * 2);
        else UVTrace.HideAll();
    }

    private void UpdateUV(float deltaTime)
    {
        Transform beam = uv.Light.transform;
        float cosine = Mathf.Cos(uv.Light.spotAngle * 0.5f * Mathf.Deg2Rad);
        Shader.SetGlobalVector(UVPositionId, beam.position);
        Shader.SetGlobalVector(UVDirectionId, beam.forward);
        Shader.SetGlobalVector(UVParamsId, new Vector4(cosine, uv.Light.range, 1, 0));
        UVTrace.UpdateAll(beam.position, beam.forward, cosine, uv.Light.range, deltaTime);
    }

    private void Switch(Torch torch, bool on)
    {
        if (torch.Light == null)
        {
            if (!on) return;
            Create(torch);
        }
        if (FlashlightCookie != null) torch.Light.cookie = FlashlightCookie;
        if (on) Attach(torch);
        torch.Light.enabled = on;
        // Off means inactive too, so the scene's light budget checks do not count it.
        torch.Light.gameObject.SetActive(on);
        if (torch.Model != null) torch.Model.SetActive(on);
    }

    private void Create(Torch torch)
    {
        GameObject holder = new GameObject(torch.Ultraviolet ? "UVTorch" : "Flashlight");
        Light light = holder.AddComponent<Light>();
        light.type = LightType.Spot;
        if (torch.Ultraviolet)
        {
            light.range = UVRange;
            light.spotAngle = UVSpotAngle;
            light.intensity = UVIntensity;
            light.color = UVColor;
            light.shadows = LightShadows.None;
        }
        else
        {
            light.range = 14;
            light.spotAngle = 42;
            light.intensity = FlashlightIntensity;
            light.color = FlashlightColor;
            light.shadows = LightShadows.Hard;
            light.shadowResolution = UnityEngine.Rendering.LightShadowResolution.Low;
        }
        torch.Light = light;
        torch.Model = DemoToolGeometry.CreateFlashlight(torch.Ultraviolet);
        torch.Model.transform.SetParent(holder.transform, false);
        torch.Parts = torch.Model.GetComponentsInChildren<Renderer>(true);
        Camera.onPreCull -= HideModelFrom;
        Camera.onPreCull += HideModelFrom;
        Camera.onPostRender -= ShowModelAfter;
        Camera.onPostRender += ShowModelAfter;
    }

    // A desktop torch belongs to the presenter's view only: evidence photos taken
    // from the view pose and the DSLR viewfinder render without it. In the hand a
    // torch is a real object and stays visible to every camera.
    private void HideModelFrom(Camera cam)
    {
        Hide(white, cam);
        Hide(uv, cam);
    }

    private static void Hide(Torch torch, Camera cam)
    {
        if (torch.Hidden || torch.Model == null || !torch.Model.activeInHierarchy || cam == Camera.main
            || torch.Model.transform.parent == torch.Light.transform) return;
        torch.Hidden = true;
        foreach (Renderer r in torch.Parts)
            if (r != null) r.forceRenderingOff = true;
    }

    private void ShowModelAfter(Camera cam)
    {
        Show(white);
        Show(uv);
    }

    private static void Show(Torch torch)
    {
        if (!torch.Hidden) return;
        torch.Hidden = false;
        foreach (Renderer r in torch.Parts)
            if (r != null) r.forceRenderingOff = false;
    }

    // The main camera on the desktop; the torch's own hand (white right, UV left)
    // while VR drives the rig.
    private void Attach(Torch torch)
    {
        if (mode == null) mode = FindFirstObjectByType<DemoModeSwitch>();
        torch.InVR = mode != null && mode.VRActive;
        Transform holder = null;
        if (torch.InVR)
            foreach (XRControllerInput hand in FindObjectsByType<XRControllerInput>(FindObjectsInactive.Include, FindObjectsSortMode.None))
                if (hand.Node == torch.Hand) holder = hand.transform;
        bool onView = holder == null;
        if (onView) holder = Camera.main != null ? Camera.main.transform : transform;
        Light light = torch.Light;
        light.transform.SetParent(holder, false);
        // On the view the light and the model both aim at the view axis 4 m ahead, so
        // the beam lands where the presenter looks; in the hand it points along the hand.
        Vector3 lens = onView ? Side(ViewLightOffset, torch) : HandLensOffset;
        light.transform.localPosition = lens;
        light.transform.localRotation = onView ? Quaternion.LookRotation(new Vector3(0, 0, 4) - lens) : Quaternion.identity;
        Transform model = torch.Model.transform;
        Vector3 at = Side(ViewModelOffset, torch);
        model.SetParent(onView ? holder : light.transform, false);
        model.localPosition = onView ? at : Vector3.zero;
        model.localRotation = onView ? Quaternion.LookRotation(new Vector3(0, 0, 4) - at) : Quaternion.identity;
        model.localScale = Vector3.one * (onView ? ViewModelScale : 1);
    }

    // The UV torch mirrors the white torch's desktop offsets to the left of the view.
    private static Vector3 Side(Vector3 offset, Torch torch) => torch.Ultraviolet ? new Vector3(-offset.x, offset.y, offset.z) : offset;

    private void OnDestroy()
    {
        Camera.onPreCull -= HideModelFrom;
        Camera.onPostRender -= ShowModelAfter;
        foreach (Torch torch in new[] { white, uv })
        {
            if (torch.Model != null) Destroy(torch.Model);
            if (torch.Light != null) Destroy(torch.Light.gameObject);
        }
        Shader.SetGlobalVector(UVParamsId, Vector4.zero);
    }
}
